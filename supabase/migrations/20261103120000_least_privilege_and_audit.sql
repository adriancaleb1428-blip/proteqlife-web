-- Least-privilege grants, role-scoped course management and audit trail.
-- RLS already filters rows; these grants remove capabilities the browser
-- never needs, so a policy mistake cannot be turned into a write or TRUNCATE.

-- 1. Anonymous visitors never read or write classroom data.
revoke all on all tables in schema public from anon;
revoke all on all sequences in schema public from anon;
revoke execute on all functions in schema public from anon;
alter default privileges for role postgres in schema public revoke all on tables from anon;
alter default privileges for role postgres in schema public revoke all on sequences from anon;
alter default privileges for role postgres in schema public revoke execute on functions from anon;

-- 2. Signed-in users: no TRUNCATE (bypasses RLS), REFERENCES or TRIGGER.
revoke truncate, references, trigger on all tables in schema public from authenticated;
alter default privileges for role postgres in schema public revoke truncate, references, trigger on tables from authenticated;

-- 3. Profiles: rows are created by handle_new_user and roles change only
-- through the admin-users Edge Function (service role). Users may edit only
-- their display fields.
revoke insert, update, delete on public.profiles from authenticated;
grant update (full_name, avatar_url, timezone) on public.profiles to authenticated;

-- 4. Notifications are generated by triggers. Users may only mark them read;
-- administrators keep DELETE for the history screen.
revoke insert, update on public.notifications from authenticated;
grant update (read_at) on public.notifications to authenticated;

-- 5. Only administrators create or delete courses (README role model).
drop policy if exists course_insert on public.courses;
create policy course_insert on public.courses for insert to authenticated
  with check ((select private.is_admin()) and created_by = (select auth.uid()));
drop policy if exists course_delete on public.courses;
create policy course_delete on public.courses for delete to authenticated
  using ((select private.is_admin()));

-- 6. An instructor assignment only grants management when can_manage is set.
create or replace function private.can_manage_course(target uuid) returns boolean
language sql stable security definer set search_path = '' as $$
  select private.is_admin()
    or exists(select 1 from public.course_instructors ci where ci.course_id = target and ci.instructor_id = (select auth.uid()) and ci.can_manage)
    or exists(select 1 from public.courses c where c.id = target and c.created_by = (select auth.uid()))
$$;

drop policy if exists notifications_admin_manage on public.notifications;
create policy notifications_admin_manage on public.notifications for all to authenticated
  using ((select private.is_admin())) with check ((select private.is_admin()));

-- 7. Audit trail for privilege-relevant changes, whatever path makes them.
create or replace function private.audit_change() returns trigger
language plpgsql security definer set search_path = '' as $$
declare
  row_data jsonb := to_jsonb(coalesce(new, old));
  event text := lower(tg_table_name || '.' || tg_op);
begin
  if tg_table_name = 'profiles' then
    if tg_op <> 'UPDATE' or new.role is not distinct from old.role then return new; end if;
    row_data := jsonb_build_object('target_user_id', new.id, 'old_role', old.role, 'new_role', new.role);
    event := 'profiles.role_changed';
  else
    row_data := row_data - 'storage_path' - 'body' - 'description';
  end if;
  insert into private.security_events (actor_id, event_type, metadata)
  values ((select auth.uid()), event, row_data);
  return coalesce(new, old);
end;
$$;
revoke all on function private.audit_change() from public, anon, authenticated;

drop trigger if exists audit_profiles_role on public.profiles;
create trigger audit_profiles_role after update of role on public.profiles
  for each row execute function private.audit_change();
drop trigger if exists audit_enrollments on public.enrollments;
create trigger audit_enrollments after insert or update or delete on public.enrollments
  for each row execute function private.audit_change();
drop trigger if exists audit_course_instructors on public.course_instructors;
create trigger audit_course_instructors after insert or update or delete on public.course_instructors
  for each row execute function private.audit_change();
drop trigger if exists audit_courses_delete on public.courses;
create trigger audit_courses_delete after delete on public.courses
  for each row execute function private.audit_change();
drop trigger if exists audit_course_certificates on public.course_certificates;
create trigger audit_course_certificates after insert or delete on public.course_certificates
  for each row execute function private.audit_change();

-- 8. Suspicious-activity summary for administrators (SQL editor / dashboards):
-- rate-limit hits, role changes and mass deletions in the last 24 hours.
create or replace view private.suspicious_activity_24h as
  select actor_id, event_type, count(*) as events, min(occurred_at) as first_seen, max(occurred_at) as last_seen
  from private.security_events
  where occurred_at > now() - interval '24 hours'
    and (event_type like 'rate_limit.%' or event_type in ('profiles.role_changed', 'courses.delete', 'enrollments.delete', 'course_certificates.delete'))
  group by actor_id, event_type
  order by events desc;
revoke all on private.suspicious_activity_24h from public, anon, authenticated;

-- 9. The previous self-update policy re-queried profiles inside its own
-- WITH CHECK, which raised "infinite recursion" for every profile update.
-- Column grants above already make role/can_create_courses read-only.
drop policy if exists profile_update_self on public.profiles;
create policy profile_update_self on public.profiles for update to authenticated
  using (id = (select auth.uid())) with check (id = (select auth.uid()));
